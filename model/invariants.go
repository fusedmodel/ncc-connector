package model

// SharedInvariants 五类内容（kb / mem / ckpt / trace 与用户自己声明的集合）**共用**的口径。
//
// 为什么要有这一份：下面这几条不是"各自的最佳实践"，而是同一个产品的**同一条口径** ——
// 归档是归档、删是删；读不到要说清原因；跨空间要授权；过期是读时判定。
// 各写一遍，三个月后一定有一条不一样，然后用户就得记住"kb 是这样、mem 是那样" ——
// 那是设计漏了口子，不是用户该操心的复杂度。
//
// 所以这是一份**代码里的常量**，五个 `/kinds` 接口都返回它，
// 冒烟断言五份**逐字相同**（不一样就红）。要改口径就改这里，一处改、五处生效。
func SharedInvariants() []string {
	return []string{
		"归档 ≠ 删除：归档只是默认不列出（指定 `archived=1` 还能看到），删要显式说",
		"读不到 ≠ 没有：读不到时说清原因（不存在 / 不是你的 / 已过期），不给一个空结果",
		"CRUD ≠ 授权：写要命名空间成员，跨空间读要 grant —— 能写不等于能读别人的",
		"过期即不存在：过期在**读时**判定（不等清理任务），gc 只是清垃圾",
		"动态 ≠ 无模式：没声明的字段、不能过滤的字段，明确拒绝而不是默默忽略",
	}
}
